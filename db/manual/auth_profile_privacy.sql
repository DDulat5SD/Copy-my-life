-- Sign out (US-02) and personal profile (US-03).
--
-- NOT run automatically. With spring.jpa.hibernate.ddl-auto=update the application makes these
-- same changes on start; this script is only needed if that setting is ever turned off.
-- It only adds: one new table and three nullable columns. No user row is changed: existing
-- accounts keep NULL interests, goals and token_version (NULL counts as version 0, so every
-- token issued before the release keeps working).
-- The previous release ignores the table and columns. After a rollback, signed-out tokens and
-- tokens from before a password reset would be accepted again until they expire (24 hours).
-- Safe to run more than once.
--
-- Usernames are NOT given a unique index: earlier accounts already share some usernames, and
-- this script changes no account. The application refuses a new or changed username that is
-- already taken, ignoring case.

-- Read-only: usernames shared by more than one account (left as they are).
SELECT lower(username) AS username, count(*) AS accounts
FROM users
WHERE username IS NOT NULL
GROUP BY lower(username)
HAVING count(*) > 1;

BEGIN;

ALTER TABLE users ADD COLUMN IF NOT EXISTS interests VARCHAR(500);
ALTER TABLE users ADD COLUMN IF NOT EXISTS goals VARCHAR(500);
ALTER TABLE users ADD COLUMN IF NOT EXISTS token_version INTEGER;

CREATE TABLE IF NOT EXISTS revoked_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    user_id    BIGINT NOT NULL,
    CONSTRAINT uk_revoked_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_revoked_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_revoked_tokens_expires_at ON revoked_tokens (expires_at);

COMMIT;
