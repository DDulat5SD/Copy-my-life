-- Weekly Routine Calendar (US-27): change or delete one occurrence of a repeating event.
--
-- NOT run automatically. With spring.jpa.hibernate.ddl-auto=update the application makes these
-- same changes on start; this script is only needed if that setting is ever turned off.
-- It only adds: one new table, two nullable columns and their foreign keys. No existing
-- calendar event is changed or deleted; every existing event keeps NULL in the new columns.
-- The previous release ignores the table and columns. If it deletes a series, the foreign keys
-- remove that series' exceptions and changed days with it, so rolling back needs no database step.
-- Safe to run more than once.

BEGIN;

CREATE TABLE IF NOT EXISTS calendar_event_exceptions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    occurrence_date DATE   NOT NULL,
    event_id        BIGINT NOT NULL,
    CONSTRAINT uk_calendar_exception_day UNIQUE (event_id, occurrence_date),
    CONSTRAINT fk_calendar_exception_event FOREIGN KEY (event_id) REFERENCES calendar_events (id) ON DELETE CASCADE
);

ALTER TABLE calendar_events ADD COLUMN IF NOT EXISTS original_date DATE;
ALTER TABLE calendar_events ADD COLUMN IF NOT EXISTS series_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'calendar_events'::regclass AND contype = 'f'
          AND pg_get_constraintdef(oid) LIKE 'FOREIGN KEY (series_id)%'
    ) THEN
        ALTER TABLE calendar_events
            ADD CONSTRAINT fk_calendar_event_series FOREIGN KEY (series_id) REFERENCES calendar_events (id) ON DELETE CASCADE;
    END IF;
END $$;

COMMIT;
