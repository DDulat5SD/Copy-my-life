-- Follow a Creator (US-13): table user_follows.
--
-- NOT run automatically. With spring.jpa.hibernate.ddl-auto=update the application
-- creates this same table on start, so this script is only needed if that setting is
-- ever turned off or the table must exist before the release. Safe to run more than once.
-- It only adds a new table; no existing row in any table is read or changed.

BEGIN;

CREATE TABLE IF NOT EXISTS user_follows (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMP(6) NOT NULL,
    follower_id  BIGINT       NOT NULL,
    following_id BIGINT       NOT NULL,
    CONSTRAINT uk_user_follows_pair UNIQUE (follower_id, following_id),
    CONSTRAINT ck_user_follows_not_self CHECK (follower_id <> following_id),
    CONSTRAINT fk_user_follows_follower FOREIGN KEY (follower_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_follows_following FOREIGN KEY (following_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_user_follows_following ON user_follows (following_id);

COMMIT;
